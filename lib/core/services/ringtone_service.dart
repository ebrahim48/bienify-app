import 'dart:async';

import 'package:audioplayers/audioplayers.dart';
import 'package:flutter/foundation.dart';
import 'package:vibration/vibration.dart';

/// Which tone a call is playing.
enum Ringtone {
  /// The bright arpeggio the callee hears, with a vibration pattern under it.
  incoming,

  /// The duller ringback the caller hears while they wait.
  outgoing,
}

/// The sound a call makes.
///
/// An interface so a screen can be built, tested and rendered without an audio
/// device: the widget tests drive [SilentRingtoneService], which no amount of
/// mocking an `AudioPlayer` would allow.
abstract class RingtoneService {
  /// Starts looping [tone], replacing whatever was playing.
  Future<void> start(Ringtone tone);

  /// Stops, and stops vibrating. Safe to call when nothing is playing — every
  /// path out of a call ends up here, and several of them can arrive at once.
  Future<void> stop();

  Future<void> dispose();
}

/// The real one.
///
/// Both tones are generated WAVs under `assets/sounds/`, rather than a
/// downloaded ringtone: a recognisable ringtone is somebody's copyright, and a
/// tone generated by `tools/generate_call_tones.py` can be changed by whoever
/// wants it a semitone lower.
class AudioRingtoneService implements RingtoneService {
  AudioRingtoneService({AudioPlayer? player, this.canVibrate})
    : _injected = player;

  final AudioPlayer? _injected;

  /// Built on the first ring, not in the constructor.
  ///
  /// This service is registered at start-up, and constructing an `AudioPlayer`
  /// reaches for a platform channel — which in a widget test, or on a platform
  /// with no plugin implementation, means dependency injection itself throws
  /// and the app never starts. A silent ringtone is a bug; a start-up crash is
  /// a much larger one.
  AudioPlayer? _created;

  AudioPlayer get _player =>
      _injected ?? (_created ??= AudioPlayer(playerId: 'bienify-ringtone'));

  /// Overridden in tests. Null asks the device.
  final bool? canVibrate;

  static const Map<Ringtone, String> _assets = {
    Ringtone.incoming: 'sounds/incoming_call.wav',
    Ringtone.outgoing: 'sounds/outgoing_call.wav',
  };

  /// Long enough to cover the ring's own silence, so the phone buzzes once per
  /// tone rather than continuously. `[wait, buzz, wait, buzz…]`.
  static const List<int> _vibrationPattern = [0, 700, 900, 700, 1700];

  Ringtone? _playing;

  @override
  Future<void> start(Ringtone tone) async {
    if (_playing == tone) return;
    await stop();
    _playing = tone;

    try {
      await _player.setReleaseMode(ReleaseMode.loop);
      // `alarm` on the incoming tone so it is heard through a silenced media
      // volume — a consultation being missed because the last thing the phone
      // played was a muted video is the failure this whole feature exists to
      // prevent.
      await _player.setAudioContext(
        tone == Ringtone.incoming
            ? AudioContextConfig(
                focus: AudioContextConfigFocus.duckOthers,
                route: AudioContextConfigRoute.speaker,
              ).build()
            : AudioContextConfig(
                focus: AudioContextConfigFocus.duckOthers,
              ).build(),
      );
      await _player.play(AssetSource(_assets[tone]!));
    } catch (err) {
      // A device with no audio output, or a platform the plugin has no
      // implementation for. The call still rings visually; it must not fail to
      // arrive because it could not be heard.
      debugPrint('RingtoneService: could not play $tone: $err');
    }

    if (tone == Ringtone.incoming) await _startVibrating();
  }

  Future<void> _startVibrating() async {
    try {
      if (!(canVibrate ?? await Vibration.hasVibrator())) return;
      await Vibration.vibrate(pattern: _vibrationPattern, repeat: 0);
    } catch (err) {
      debugPrint('RingtoneService: could not vibrate: $err');
    }
  }

  @override
  Future<void> stop() async {
    if (_playing == null) return;
    _playing = null;
    try {
      await _player.stop();
    } catch (_) {
      // Stopping a player that never started is not a failure worth surfacing.
    }
    try {
      await Vibration.cancel();
    } catch (_) {
      // Same.
    }
  }

  @override
  Future<void> dispose() async {
    await stop();
    // Only what was actually built — reaching for `_player` here would create
    // a player purely in order to throw it away.
    await _created?.dispose();
    _created = null;
  }
}

/// Rings nothing. Used by widget tests, which have no audio device, and as the
/// fallback on a platform where the plugin is unavailable.
class SilentRingtoneService implements RingtoneService {
  /// What was asked for, so a test can assert the call actually rang.
  Ringtone? playing;

  @override
  Future<void> start(Ringtone tone) async => playing = tone;

  @override
  Future<void> stop() async => playing = null;

  @override
  Future<void> dispose() async => playing = null;
}
